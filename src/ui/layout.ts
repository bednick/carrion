import Phaser from 'phaser';

// Модель координат экрана.
//
// Высота логического холста фиксирована (800), ширина вычисляется из аспекта окна — так аспект холста
// совпадает с аспектом окна и Scale.FIT не оставляет полос. Исторический дизайн рисовался в 1280×800;
// вся раскладка сохраняется, но «переезжает» в новый центр:
//
//   - центрированный элемент          640              → CX
//   - заливка/оверлей во всю ширину   (640, w=1280)    → (CX, w=GAME_W)
//   - прижато к правому краю          1280 - off       → rightX(off)
//   - прижато к левому краю           10               → без изменений
//   - кластер со смещённым центром    560, 700+slot*160 → + DX (боевая арена экспедиции)
//
// Ширина пересчитывается на лету (F11, изменение размера окна) — см. recomputeLayout и src/ui/resize.ts.
// Поэтому GAME_W/CX/DX объявлены через `let`: ES-модули отдают живые привязки, и все места использования
// подхватывают новое значение сами. А вот производные константы, вычисленные ОДИН раз на уровне модуля или
// поля класса, после пересчёта протухнут — такие значения обязаны быть функциями (примеры: heroX() в
// ExpeditionScene, геометрия VolumeControl). См. docs/ui.md.

/** Историческая ширина дизайна — база, относительно которой выверены все координаты. */
export const BASE_W = 1280;

/** Высота логического холста. Фиксирована навсегда — вся вертикальная раскладка на неё опирается. */
export const GAME_H = 800;

/** Потолок ширины (2.4:1). Шире — снова появятся полосы, но такие экраны редки. */
export const MAX_W = 1920;

/** Разница ширины, ниже которой пересчёт считается шумом и не вызывает перекладку сцен. */
const WIDTH_EPSILON = 4;

function computeWidth(): number {
  // Уже дизайна (окно вытянуто вверх) — остаёмся на BASE_W, тогда FIT даст леттербокс сверху/снизу,
  // это принятый компромисс. Округляем до чётного — дружелюбнее к roundPixels.
  const raw = Phaser.Math.Clamp(GAME_H * (window.innerWidth / window.innerHeight), BASE_W, MAX_W);
  return Math.round(raw / 2) * 2;
}

/** Ширина логического холста. */
export let GAME_W = computeWidth();

/** Горизонтальный центр экрана. */
export let CX = GAME_W / 2;

/** Сдвиг «дизайнового» кластера 1280 в новый центр. */
export let DX = CX - BASE_W / 2;

/**
 * Пересчитывает ширину под текущий размер окна.
 * Возвращает true, если ширина изменилась настолько, что раскладку нужно пересобрать.
 */
export function recomputeLayout(): boolean {
  const next = computeWidth();
  if (Math.abs(next - GAME_W) < WIDTH_EPSILON) return false;
  GAME_W = next;
  CX = GAME_W / 2;
  DX = CX - BASE_W / 2;
  return true;
}

/** Дизайновая высота панели меню НПС в лагере — база масштаба ячеек. */
const PANEL_DESIGN_H = 520;
/** Вертикальный отступ панели от краёв холста. */
const PANEL_PAD = 70;

/**
 * Масштаб панели меню НПС (лагерь). Панель растягивается по высоте холста, но не сжимается ниже 1
 * и не вылезает за левый край (вкладки торчат до 540 левее пивота).
 *
 * Экспедиция масштабирует свои ячейки экипировки/рюкзака этим же коэффициентом — иначе один и тот же
 * предмет в лагере и в бою выглядел бы разного размера.
 */
export function panelScale(): number {
  const desired = (GAME_H - 2 * PANEL_PAD) / PANEL_DESIGN_H;
  const maxByWidth = (CX - 8) / 540;
  return Math.max(1, Math.min(desired, maxByWidth));
}

/** X по отступу от правого края. */
export function rightX(offsetFromRight: number): number {
  return GAME_W - offsetFromRight;
}
