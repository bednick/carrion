import Phaser from 'phaser';

// Модель координат экрана.
//
// Высота логического холста фиксирована (800), ширина вычисляется из аспекта окна на старте — так аспект
// холста совпадает с аспектом монитора и Scale.FIT не оставляет боковых полос. Исторический дизайн рисовался
// в 1280×800; вся раскладка сохраняется, но «переезжает» в новый центр:
//
//   - центрированный элемент          640              → CX
//   - заливка/оверлей во всю ширину   (640, w=1280)    → (CX, w=GAME_W)
//   - прижато к правому краю          1280 - off       → rightX(off)
//   - прижато к левому краю           10               → без изменений
//   - кластер со смещённым центром    560, 700+slot*160 → + DX (боевая арена экспедиции)
//
// Ресайз окна на лету не поддерживается: ширина считается один раз при импорте (до создания Phaser.Game),
// при изменении размера окна FIT просто масштабирует холст. См. docs/ui.md.

/** Историческая ширина дизайна — база, относительно которой выверены все координаты. */
export const BASE_W = 1280;

/** Высота логического холста. Фиксирована навсегда — вся вертикальная раскладка на неё опирается. */
export const GAME_H = 800;

/** Потолок ширины (2.4:1). Шире — снова появятся полосы, но такие экраны редки. */
export const MAX_W = 1920;

/**
 * Ширина логического холста. Уже дизайна (окно вытянуто вверх) — остаёмся на BASE_W, тогда FIT даст
 * леттербокс сверху/снизу, это нормально. Округляем до чётного — дружелюбнее к roundPixels.
 */
export const GAME_W = Math.round(
  Phaser.Math.Clamp(GAME_H * (window.innerWidth / window.innerHeight), BASE_W, MAX_W) / 2,
) * 2;

/** Горизонтальный центр экрана. */
export const CX = GAME_W / 2;

/** Сдвиг «дизайнового» кластера 1280 в новый центр. */
export const DX = CX - BASE_W / 2;

/** X по отступу от правого края. */
export function rightX(offsetFromRight: number): number {
  return GAME_W - offsetFromRight;
}
